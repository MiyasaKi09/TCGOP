// Verify deck sizes
function verifyDeck(deck: DeckDef): void {
  const total = deck.cards.reduce((sum, e) => sum + e.count, 0);
  if (total !== 50) {
    console.warn(`Deck "${deck.name}" has ${total} cards (expected 50)`);
  }
}

